export async function POST() {
  try {
    await dbConnect();

    const existing = await StayListing.countDocuments({ isDemo: true });
    if (existing >= 10) {
      return NextResponse.json({ message: "Demo stays already seeded", count: existing });
    }

    // Remove old demo stays to avoid slug conflicts
    await StayListing.deleteMany({ isDemo: true });

    // Use a fake ObjectId for demo providerId
    const fakeId = "000000000000000000000001";
    const staysWithProvider = DEMO_STAYS.map((s) => ({
      ...s,
      providerId: fakeId,
      providerProfileId: fakeId,
    }));

    const inserted = await StayListing.insertMany(staysWithProvider);
    return NextResponse.json({ message: `Seeded ${inserted.length} demo stays!`, count: inserted.length });
  } catch (err) {
    console.error("Stays seed error:", err);
    return NextResponse.json({ error: "Failed to seed stays" }, { status: 500 });
  }
}
